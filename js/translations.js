// Language management
let currentLanguage = localStorage.getItem('dronewatch-language') || 'en';

function setLanguage(lang) {
  if (!translations[lang]) {
    console.warn(`Language ${lang} not supported, falling back to English`);
    lang = 'en';
  }

  currentLanguage = lang;
  localStorage.setItem('dronewatch-language', lang);
  updatePageTranslations();
}

function t(key, params = {}) {
  const translation = translations[currentLanguage]?.[key] || translations['en'][key] || key;

  // Replace parameters like {n} with actual values
  return translation.replace(/\{(\w+)\}/g, (match, paramName) => {
    return params[paramName] || match;
  });
}

function updatePageTranslations() {
  // Update all elements with data-translate attribute
  document.querySelectorAll('[data-translate]').forEach(element => {
    const key = element.getAttribute('data-translate');
    element.textContent = t(key);
  });

  // Update placeholders
  document.querySelectorAll('[data-translate-placeholder]').forEach(element => {
    const key = element.getAttribute('data-translate-placeholder');
    element.placeholder = t(key);
  });

  // Update title attributes
  document.querySelectorAll('[data-translate-title]').forEach(element => {
    const key = element.getAttribute('data-translate-title');
    element.title = t(key);
  });

  // Update page title
  document.title = `${t('title')} - ${t('tagline')}`;
}

// Initialize on load
document.addEventListener('DOMContentLoaded', updatePageTranslations);

// Export for use in other modules
window.DroneWatchTranslations = {
  setLanguage,
  t,
  currentLanguage: () => currentLanguage,
  availableLanguages: Object.keys(translations)
};